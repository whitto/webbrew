"""Generate a self-contained Arduino IDE sketch from the shared firmware/UI.

Run with --check in CI to detect stale generated files. No PlatformIO is needed
to open, compile or upload the committed sketch in Arduino IDE.
"""
import argparse
from pathlib import Path
from web_header import make_header

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "arduino"
NOTICE = "// Generated by scripts/export_arduino.py; edit the shared source instead.\n"


def files(variant):
    page = (ROOT / "web" / "index.html").read_bytes()
    sous_vide = variant == "SousVide"
    if sous_vide:
        page = page.replace(b'content="brew"', b'content="sousvide"')
    header = make_header(page)
    flags = "#define WEBBREW_SOUSVIDE 1\n" if sous_vide else ""
    return {
        f"{variant}.ino": (
            f"// {variant} v0.3 — open this file in Arduino IDE 2.x.\n"
            "// Select ESP32 Dev Module with esp32 by Espressif Systems 2.0.17.\n"
            "// Install OneWire 2.3.8, DallasTemperature 3.11.0 and ArduinoJson 7.2.1.\n"
            "// setup() and loop() live in firmware.cpp to avoid sketch prototype rewriting.\n"
            "// Keep all files in this folder together. See ../README.md.\n"
            "#include <Arduino.h>\n"
        ),
        "firmware.cpp": NOTICE + flags + (ROOT / "src" / "main.cpp").read_text(),
        "controller.h": NOTICE + (ROOT / "include" / "controller.h").read_text(),
        "web_page.h": NOTICE + header,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    for variant in ("WebBrew", "SousVide"):
        dest = DEST / variant
        if not args.check:
            dest.mkdir(parents=True, exist_ok=True)
        for name, content in files(variant).items():
            path = dest / name
            if args.check:
                if not path.exists() or path.read_text() != content:
                    stale.append(str(path.relative_to(ROOT)))
            else:
                path.write_text(content)
    if stale:
        parser.exit(1, "Outdated Arduino export: " + ", ".join(stale) + "\nRun python3 scripts/export_arduino.py\n")
    print("Arduino sketch matches shared firmware and dashboard." if args.check else f"Exported {DEST.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
